package array;

public class Arraybasic {
    public static void main(String[] args) {
        int [] x={12,23,45,34,23,23};
        //indexing
        System.out.println(x[3]);//accessing
        x[3]=56;
        System.out.println(x[3]);//updating
        int[] arr = new  int[3];//creating empty array
        arr[0]=12;
        arr[1]=22;
        arr[2]=32;
        System.out.println(arr[0]);
        System.out.println(arr[1]);
        System.out.println(arr[2]);

        
    }
    
}
